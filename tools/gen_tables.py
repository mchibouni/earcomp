"""Turn the measured Mimi map (data/mimi-map.json) into src/MimiTables.h.

The map holds Mimi's steady-state gain (dB) for a sine at each frequency x input level,
for the three presets the extension shows: Recommended (default), Richer (up), Softer (down).
Mimi applies the same gain to both channels, so only L is used."""
import json, pathlib

root = pathlib.Path(__file__).resolve().parent.parent
m = json.loads((root / 'data/mimi-map.json').read_text())
freqs, levels = m['freqs'], m['levels']
variants = [('Recommended', 'default'), ('Richer', 'up'), ('Softer', 'down')]

out = ['// Generated by tools/gen_tables.py from data/mimi-map.json. Do not edit.',
       '#pragma once', '', 'namespace earcomp {', '',
       f'constexpr int kTableFreqs = {len(freqs)};',
       f'constexpr int kTableLevels = {len(levels)};',
       f'constexpr int kTableVariants = {len(variants)};',
       f'constexpr float kTableLevelMin = {levels[0]:.1f}f;',
       f'constexpr float kTableLevelStep = {levels[1] - levels[0]:.1f}f;',
       'constexpr float kTableFreqHz[kTableFreqs] = {' + ', '.join(f'{f:.1f}f' for f in freqs) + '};',
       'constexpr const char* kVariantNames[kTableVariants] = {' + ', '.join(f'"{n}"' for n, _ in variants) + '};',
       '', '// kGainDb[variant][level][freq]',
       'constexpr float kGainDb[kTableVariants][kTableLevels][kTableFreqs] = {']
for name, key in variants:
    out.append(f'  {{ // {name}')
    for lev, row in zip(levels, m['static'][key]['L']):
        out.append('    {' + ', '.join(f'{g:.2f}f' for g in row) + f'}}, // {lev} dBFS')
    out.append('  },')
out += ['};', '', '} // namespace earcomp', '']
(root / 'src/MimiTables.h').write_text('\n'.join(out))
print('wrote src/MimiTables.h', len(variants), 'x', len(levels), 'x', len(freqs))
